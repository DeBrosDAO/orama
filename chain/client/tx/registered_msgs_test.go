package tx_test

import (
	"encoding/json"
	"sort"
	"strings"
	"testing"

	"github.com/stretchr/testify/require"

	"github.com/cosmos/cosmos-sdk/codec"
	sdk "github.com/cosmos/cosmos-sdk/types"
)

// registeredMsgsPath lists every message the chain registers, with the JSON the
// indexer serves for it (an all-zero message, so every field name is present).
// The website explorer's completeness test reads it: a message the chain gains
// must have a decoder there before this file can be regenerated and shipped.
const registeredMsgsPath = "testdata/registered_msgs.json"

type registeredMsgs struct {
	Comment string                     `json:"comment"`
	Msgs    []string                   `json:"msgs"`
	Shapes  map[string]json.RawMessage `json:"shapes"`
}

// TestRegisteredMsgs_listIsPinned records every Msg in the chain app's interface
// registry and its protojson shape. Regenerate with
// go test ./client/tx -run TestRegisteredMsgs -update-tx-vectors.
func TestRegisteredMsgs_listIsPinned(t *testing.T) {
	registry := oramaInterfaceRegistry(t)
	urls := registry.ListImplementations(sdk.MsgInterfaceProtoName)
	sort.Strings(urls)
	require.NotEmpty(t, urls)
	linked := false
	for _, url := range urls {
		linked = linked || strings.HasPrefix(url, "/cosmwasm.")
	}
	if !linked {
		t.Skip("this build does not link CosmWasm, so the registry lacks its messages; the pinned list includes them")
	}

	cdc := codec.NewProtoCodec(registry)
	shapes := make(map[string]json.RawMessage, len(urls))
	for _, url := range urls {
		msg, err := registry.Resolve(url)
		require.NoError(t, err, url)
		js, err := cdc.MarshalInterfaceJSON(msg)
		require.NoError(t, err, "encode %s as the indexer does", url)
		shapes[url] = js
	}
	writeOrCompare(t, registeredMsgsPath, registeredMsgs{
		Comment: "Generated by chain/client/tx registered_msgs_test.go. Every Msg the chain app registers and its all-zero protojson, as the indexer serves a message body. Do not edit; run go test ./client/tx -run TestRegisteredMsgs -update-tx-vectors.",
		Msgs:    urls,
		Shapes:  shapes,
	})
}
