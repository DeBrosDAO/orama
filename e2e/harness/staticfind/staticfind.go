// Package staticfind reads the output of `staticcheck -f json` and drops the
// one kind of finding the repository cannot fix: a deprecated API used by
// grpc-gateway v1 generated code.
package staticfind

import (
	"bufio"
	"bytes"
	"encoding/json"
	"fmt"
	"os"
	"strings"
)

const (
	// deprecated is staticcheck's check for the use of a deprecated API.
	deprecated = "SA1019"
	// gatewayHeader begins the first line of a file protoc-gen-grpc-gateway
	// wrote.
	gatewayHeader = "// Code generated by protoc-gen-grpc-gateway"
)

// Finding is one problem staticcheck reported.
type Finding struct {
	Code     string `json:"code"`
	Severity string `json:"severity"`
	Message  string `json:"message"`
	Location struct {
		File   string `json:"file"`
		Line   int    `json:"line"`
		Column int    `json:"column"`
	} `json:"location"`
}

// String is the finding as staticcheck prints it in its text format.
func (f Finding) String() string {
	return fmt.Sprintf("%s:%d:%d: %s (%s)", f.Location.File, f.Location.Line, f.Location.Column, f.Message, f.Code)
}

// Parse reads staticcheck's JSON output, one object per line. A line that is
// not a finding is an error: a linter that printed something else did not lint.
func Parse(out []byte) ([]Finding, error) {
	var found []Finding
	sc := bufio.NewScanner(bytes.NewReader(out))
	sc.Buffer(make([]byte, 0, 64*1024), 1<<20)
	for sc.Scan() {
		line := strings.TrimSpace(sc.Text())
		if line == "" {
			continue
		}
		var f Finding
		if err := json.Unmarshal([]byte(line), &f); err != nil || f.Code == "" {
			return nil, fmt.Errorf("staticcheck -f json printed a line that is not a finding: %.200q", line)
		}
		found = append(found, f)
	}
	if err := sc.Err(); err != nil {
		return nil, fmt.Errorf("failed to read staticcheck output: %w", err)
	}
	return found, nil
}

// Remaining drops the deprecation findings (SA1019) in files that
// protoc-gen-grpc-gateway v1 generated: that generator's output imports
// github.com/golang/protobuf and calls grpc.Dial, as every cosmos-sdk module's
// does, and cannot be regenerated without it (v2's needs messages that
// implement the protobuf APIv2, which gogoproto's do not). Every other
// finding, SA1019 in hand-written code included, stays. generated reports
// whether the file at a path is one of those files.
func Remaining(found []Finding, generated func(path string) bool) []Finding {
	var out []Finding
	for _, f := range found {
		if f.Code == deprecated && generated(f.Location.File) {
			continue
		}
		out = append(out, f)
	}
	return out
}

// GeneratedByGateway reports whether the file at path begins with the header
// protoc-gen-grpc-gateway writes. A file that cannot be read is not.
func GeneratedByGateway(path string) bool {
	f, err := os.Open(path)
	if err != nil {
		return false
	}
	defer f.Close()
	first, _, _ := bufio.NewReader(f).ReadLine()
	return strings.HasPrefix(string(first), gatewayHeader)
}
