package staticfind

import (
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const sample = `{"code":"SA1019","severity":"warning","location":{"file":"/m/x/query.pb.gw.go","line":16,"column":2},"end":{"file":"/m/x/query.pb.gw.go","line":16,"column":30},"message":"github.com/golang/protobuf/proto is deprecated"}
{"code":"SA1019","severity":"warning","location":{"file":"/m/x/keeper.go","line":9,"column":3},"end":{"file":"/m/x/keeper.go","line":9,"column":9},"message":"grpc.Dial is deprecated"}
{"code":"ST1005","severity":"warning","location":{"file":"/m/x/query.pb.gw.go","line":40,"column":5},"end":{"file":"/m/x/query.pb.gw.go","line":40,"column":9},"message":"error strings should not be capitalized"}
`

func TestParse_readsOneFindingPerLine(t *testing.T) {
	got, err := Parse([]byte(sample))
	if err != nil {
		t.Fatal(err)
	}
	if len(got) != 3 || got[0].Location.File != "/m/x/query.pb.gw.go" || got[0].Location.Line != 16 || got[1].Code != "SA1019" {
		t.Fatalf("Parse = %+v", got)
	}
	if want := "/m/x/keeper.go:9:3: grpc.Dial is deprecated (SA1019)"; got[1].String() != want {
		t.Errorf("String() = %q, want %q", got[1].String(), want)
	}
}

func TestParse_emptyOutputIsNoFindings(t *testing.T) {
	got, err := Parse(nil)
	if err != nil || len(got) != 0 {
		t.Fatalf("Parse(nil) = %v, %v", got, err)
	}
}

func TestParse_refusesWhatIsNotAFinding(t *testing.T) {
	for _, out := range []string{"-: internal error in importing \"cmp\"\n", "{\"nothing\":1}\n", "[]\n"} {
		if _, err := Parse([]byte(out)); err == nil || !strings.Contains(err.Error(), "not a finding") {
			t.Errorf("Parse(%q) error = %v, want a refusal", out, err)
		}
	}
}

func TestRemaining_dropsOnlyDeprecationInGatewayCode(t *testing.T) {
	found, err := Parse([]byte(sample))
	if err != nil {
		t.Fatal(err)
	}
	got := Remaining(found, func(p string) bool { return strings.HasSuffix(p, ".pb.gw.go") })
	if len(got) != 2 || got[0].Location.File != "/m/x/keeper.go" || got[1].Code != "ST1005" {
		t.Fatalf("Remaining = %+v, want the hand-written SA1019 and the generated file's ST1005", got)
	}
}

func TestGeneratedByGateway_readsTheFirstLine(t *testing.T) {
	dir := t.TempDir()
	write := func(name, body string) string {
		p := filepath.Join(dir, name)
		if err := os.WriteFile(p, []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
		return p
	}
	if !GeneratedByGateway(write("gw.go", "// Code generated by protoc-gen-grpc-gateway. DO NOT EDIT.\npackage x\n")) {
		t.Error("a gateway-generated file was not recognised")
	}
	if GeneratedByGateway(write("pb.go", "// Code generated by protoc-gen-gogo. DO NOT EDIT.\npackage x\n")) {
		t.Error("another generator's file was taken for the gateway's")
	}
	if GeneratedByGateway(write("hand.go", "package x\n// Code generated by protoc-gen-grpc-gateway\n")) {
		t.Error("the header counts only on the first line")
	}
	if GeneratedByGateway(filepath.Join(dir, "missing.go")) {
		t.Error("a missing file was taken for generated")
	}
	if GeneratedByGateway(write("empty.go", "")) {
		t.Error("an empty file was taken for generated")
	}
}
