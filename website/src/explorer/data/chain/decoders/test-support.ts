import fs from "node:fs";
import path from "node:path";
import type { DecoderTable } from "./kit";

/**
 * The chain's own definition of its messages, read by the tests so a message
 * the chain gains cannot ship without a decoder. Two sources:
 *
 *  - `chain/proto/orama/<module>/v1/tx.proto`: the `service Msg` rpcs, whose
 *    request messages are the module's transaction messages.
 *  - `chain/client/tx/testdata/registered_msgs.json`: every Msg in the chain
 *    app's interface registry (the Orama ones and the standard Cosmos and
 *    CosmWasm ones), with each one's all-zero protojson, generated by a Go
 *    test from the app itself.
 */
const REPO_ROOT = path.resolve(import.meta.dirname, "../../../../../..");
export const PROTO_ROOT = path.join(REPO_ROOT, "chain/proto/orama");
export const REGISTERED_MSGS = path.join(REPO_ROOT, "chain/client/tx/testdata/registered_msgs.json");

export interface ProtoMsg {
  typeUrl: string;
  /** The field names of the request message, as protojson writes them. */
  fields: string[];
}

const COMMENTS = /\/\*[\s\S]*?\*\/|\/\/[^\n]*/g;
const INNER_BRACES = /\{[^{}]*\}/g;
const FIELD = /^\s*(?:repeated\s+)?[\w.]+\s+(\w+)\s*=\s*\d+/;

/** The body between the braces that open at `from`, with its nested braces left in. */
function blockAfter(source: string, from: number): string {
  const open = source.indexOf("{", from);
  let depth = 0;
  for (let i = open; i < source.length; i++) {
    if (source[i] === "{") depth++;
    if (source[i] === "}" && --depth === 0) return source.slice(open + 1, i);
  }
  throw new Error("unbalanced braces in a proto file");
}

function fieldsOf(body: string): string[] {
  let flat = body;
  while (INNER_BRACES.test(flat)) flat = flat.replace(INNER_BRACES, "");
  return flat
    .split(";")
    .map((statement) => FIELD.exec(statement)?.[1])
    .filter((name): name is string => name !== undefined);
}

/** The messages of the `service Msg` of one proto file's source: its rpcs' request types and their fields. */
export function parseMsgService(source: string): ProtoMsg[] {
  const clean = source.replace(COMMENTS, "");
  const pkg = /^\s*package\s+([\w.]+)\s*;/m.exec(clean)?.[1];
  const service = /\bservice\s+Msg\b/.exec(clean);
  if (pkg === undefined || service === null) return [];
  const requests = [...blockAfter(clean, service.index).matchAll(/\brpc\s+\w+\s*\(\s*(\w+)\s*\)/g)].map((m) => m[1] as string);
  return requests.map((name) => {
    const at = new RegExp(`\\bmessage\\s+${name}\\s*\\{`).exec(clean);
    if (at === null) throw new Error(`rpc request ${name} has no message in its proto file`);
    return { typeUrl: `/${pkg}.${name}`, fields: fieldsOf(blockAfter(clean, at.index)) };
  });
}

/** Every Msg service rpc of every `tx.proto` under chain/proto/orama. */
export function readChainTxProtos(root = PROTO_ROOT): ProtoMsg[] {
  const files = fs.readdirSync(root, { recursive: true, encoding: "utf8" }).filter((f) => path.basename(f) === "tx.proto");
  return files.sort().flatMap((f) => parseMsgService(fs.readFileSync(path.join(root, f), "utf8")));
}

export interface Registered {
  msgs: string[];
  /** The protojson of each registered message with every field zero, by type URL. */
  shapes: Record<string, Record<string, unknown>>;
}

export function readRegistered(file = REGISTERED_MSGS): Registered {
  return JSON.parse(fs.readFileSync(file, "utf8")) as Registered;
}

/** The type URLs without a decoder in `decoders`. */
export function undecoded(typeUrls: Iterable<string>, decoders: DecoderTable): string[] {
  return [...typeUrls].filter((url) => !Object.hasOwn(decoders, url)).sort();
}
