// Generates the website's gateway API page from docs/API_SURFACE.md.
//
// A Go test (core/pkg/gateway/api_surface_test.go) fails when a registered
// route is missing from that file or a documented route is no longer
// registered, so converting it here keeps the website's route list as true as
// the code. Run after docs/API_SURFACE.md changes and commit the output.
//
//   node scripts/build-api-docs.mjs          write src/docs/developer/api-surface.mdx
//   node scripts/build-api-docs.mjs --check  exit 1 if the file is out of date

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SOURCE = resolve(HERE, "../../docs/API_SURFACE.md");
const OUT = resolve(HERE, "../src/docs/developer/api-surface.mdx");

/** Where the engineering docs' relative links land on the website. */
const LINKS = new Map([
  ["CLIENT_SURFACE.md", "/docs/developer/client-surface"],
  ["SERVERLESS.md", "/docs/developer/functions"],
  ["SECURITY.md#relayed-fetch", "/docs/privacy/relayed-fetch"],
  ["SECURITY.md#function-sql", "/docs/developer/functions"],
  ["AUTH.md#fetch-capabilities", "/docs/developer/access-control#capabilities-access-without-an-identity"],
  ["ARCHITECTURE.md", "/docs/architecture/overview"],
  ["ARCHITECTURE.md#tlshttps", "/docs/operator/tls-certificates"],
]);

function escapeProse(line) {
  return line
    .split(/(`[^`]*`)/)
    .map((part, i) =>
      i % 2 === 1 ? part : part.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/\{/g, "&#123;").replace(/\}/g, "&#125;"),
    )
    .join("");
}

function convert(markdown) {
  const out = [];
  let fence = false;
  for (const raw of markdown.split("\n")) {
    if (raw.startsWith("```")) {
      fence = !fence;
      out.push(raw);
      continue;
    }
    if (fence) {
      out.push(raw);
      continue;
    }
    let line = raw.replace(/\]\(([^)]+)\)/g, (m, target) => {
      if (LINKS.has(target)) return `](${LINKS.get(target)})`;
      if (target.startsWith("http")) return m;
      // The contracts directory and any other repository path is not a page.
      return "]()";
    });
    line = line.replace(/\[([^\]]+)\]\(\)/g, "$1");
    if (/^#{3} /.test(line)) line = line.replace(/^### /, "## ");
    // A pipe inside a code span still ends a table cell, so escape it there.
    if (line.startsWith("|")) {
      line = line.replace(/`[^`]*`/g, (span) => span.replace(/(?<!\\)\|/g, "\\|"));
    }
    out.push(escapeProse(line));
  }
  const text = out.join("\n");
  return `{/* Generated by scripts/build-api-docs.mjs from docs/API_SURFACE.md. Do not edit by hand. */}\n\n${text}`.replace(/\n{3,}/g, "\n\n");
}

if (!existsSync(SOURCE)) throw new Error(`build-api-docs: ${SOURCE} is missing`);
const text = convert(readFileSync(SOURCE, "utf-8"));
if (process.argv.includes("--check")) {
  if (!existsSync(OUT) || readFileSync(OUT, "utf-8") !== text) {
    console.error(`build-api-docs: ${OUT} is out of date`);
    process.exit(1);
  }
} else {
  writeFileSync(OUT, text);
  console.log(`build-api-docs: wrote ${OUT}`);
}
