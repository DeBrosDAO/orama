// Generates the website's gateway API page from docs/whitepaper/technical-reference/appendices/i-api-surface.md.
//
// A Go test (core/pkg/gateway/api_surface_test.go) fails when a registered
// route is missing from that file or a documented route is no longer
// registered, so converting it here keeps the website's route list as true as
// the code. Run after docs/whitepaper/technical-reference/appendices/i-api-surface.md changes and commit the output.
//
//   node scripts/build-api-docs.mjs          write src/docs/developer/api-surface.mdx
//   node scripts/build-api-docs.mjs --check  exit 1 if the file is out of date

import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const SOURCE = resolve(HERE, "../../docs/whitepaper/technical-reference/appendices/i-api-surface.md");
const OUT = resolve(HERE, "../src/docs/developer/api-surface.mdx");

/** Where the appendix's relative links to whitepaper chapters land on the website. */
const LINKS = new Map([
  ["../vol1/12-gateway-architecture.md", "/docs/architecture/request-lifecycle"],
  ["../vol1/13-identity.md", "/docs/developer/sign-in"],
  ["../vol1/17-database.md#the-sql-guard", "/docs/developer/functions"],
  ["../vol1/18-cache.md", "/docs/developer/cache"],
  ["../vol1/19-storage.md#fetch-capabilities", "/docs/developer/access-control#capabilities-access-without-an-identity"],
  ["../vol1/21-serverless.md", "/docs/developer/functions"],
  ["../vol1/23-webrtc.md", "/docs/developer/webrtc"],
  ["../vol1/25-tls-and-certificates.md", "/docs/operator/tls-certificates"],
  ["../vol1/26-sni-routing-and-stealth-turn.md", "/docs/privacy/stealth-turn"],
  ["../vol1/28-vault.md", "/docs/developer/vault"],
  ["../vol1/35-the-cli.md", "/docs/developer/cli-overview"],
  ["../vol1/36-sdks.md", "/docs/developer/sdk-reference"],
  ["../vol1/36-sdks.md#relayed-fetch", "/docs/privacy/relayed-fetch"],
  ["../vol2/39-chain-architecture.md", "/docs/blockchain/modules"],
]);

function escapeProse(line) {
  return line
    .split(/(`[^`]*`)/)
    .map((part, i) =>
      i % 2 === 1 ? part : part.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/\{/g, "&#123;").replace(/\}/g, "&#125;"),
    )
    .join("");
}

function convert(markdown) {
  const out = [];
  let fence = false;
  // The appendix opens with a whitepaper "At a glance" box; the page starts at its first paragraph.
  const body = markdown.replace(/^# API surface\n\n(?:>.*\n)+\n/, "# Gateway API surface\n\n");
  for (const raw of body.split("\n")) {
    if (raw.startsWith("```")) {
      fence = !fence;
      out.push(raw);
      continue;
    }
    if (fence) {
      out.push(raw);
      continue;
    }
    let line = raw.replace(/\]\(([^)]+)\)/g, (m, target) => {
      if (LINKS.has(target)) return `](${LINKS.get(target)})`;
      if (target.startsWith("http")) return m;
      // The contracts directory and any other repository path is not a page.
      return "]()";
    });
    line = line.replace(/\[([^\]]+)\]\(\)/g, "$1");
    if (/^#{3} /.test(line)) line = line.replace(/^### /, "## ");
    // A pipe inside a code span still ends a table cell, so escape it there.
    if (line.startsWith("|")) {
      line = line.replace(/`[^`]*`/g, (span) => span.replace(/(?<!\\)\|/g, "\\|"));
    }
    out.push(escapeProse(line));
  }
  const text = out.join("\n");
  return `{/* Generated by scripts/build-api-docs.mjs from docs/whitepaper/technical-reference/appendices/i-api-surface.md. Do not edit by hand. */}\n\n${text}`.replace(/\n{3,}/g, "\n\n");
}

if (!existsSync(SOURCE)) throw new Error(`build-api-docs: ${SOURCE} is missing`);
const text = convert(readFileSync(SOURCE, "utf-8"));
if (process.argv.includes("--check")) {
  if (!existsSync(OUT) || readFileSync(OUT, "utf-8") !== text) {
    console.error(`build-api-docs: ${OUT} is out of date`);
    process.exit(1);
  }
} else {
  writeFileSync(OUT, text);
  console.log(`build-api-docs: wrote ${OUT}`);
}
